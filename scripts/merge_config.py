"""Merge the Ghidra-exported PS2Recomp TOML with SDK stubs/entry points found by ps2_analyzer."""
import sys, tomllib

def q(s):
    return '"' + s.replace(chr(92), '/') + '"'

def main(ghidra_toml, analyzer_toml, out_toml, output_dir):
    g = tomllib.load(open(ghidra_toml, 'rb'))['general']
    a = tomllib.load(open(analyzer_toml, 'rb'))['general']
    seen = {s.split('@')[-1].upper() for s in g['stubs']}
    stubs = list(g['stubs'])
    for s in a.get('stubs', []):
        addr = s.split('@')[-1].upper()
        if addr not in seen:
            seen.add(addr)
            stubs.append(s)
    lines = ['# Generated by scripts/merge_config.py from codwaw-ff.toml (Ghidra) + analyzer-heuristic.toml (SCE db).',
             '[general]',
             f'input = {q(g["input"])}',
             f'output = {q(output_dir)}',
             f'ghidra_output = {q(g["ghidra_output"])}',
             'single_file_output = false',
             'patch_syscalls = false',
             f'patch_cop0 = {str(g["patch_cop0"]).lower()}',
             f'patch_cache = {str(g["patch_cache"]).lower()}',
             'stubs = [', *[f'  {q(s)},' for s in stubs], ']',
             'entry_points = [', *[f'  {q(s)},' for s in a.get('entry_points', [])], ']',
             'skip = []']
    open(out_toml, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(stubs)} stubs, {len(a.get("entry_points", []))} entry points -> {out_toml}')

if __name__ == '__main__':
    main(*sys.argv[1:5])
