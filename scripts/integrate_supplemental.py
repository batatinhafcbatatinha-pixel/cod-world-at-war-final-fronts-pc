"""Generate a private unity include and registration helper for a supplement.

This mechanically adapts PS2Recomp output without changing instruction bodies.
Run after regeneration: python scripts/integrate_supplemental.py DIRECTORY NAME
"""
import pathlib
import re
import sys
import struct

directory = pathlib.Path(sys.argv[1])
name = sys.argv[2]
if not re.fullmatch(r"[A-Za-z_]\w*", name):
    raise SystemExit("Expected a C++ identifier for the registration helper")
registration = (directory / "register_functions.cpp").read_text()
entries = re.findall(r"g_ps2RecompiledFunctionTable\[\d+\] = (\w+); // (0x[0-9a-fA-F]+)", registration)
functions = sorted({function for function, _ in entries})
capture = pathlib.Path(sys.argv[3]).read_bytes() if len(sys.argv) == 5 else None
capture_base = int(sys.argv[4], 0) if capture is not None else 0
output = ["// Generated by scripts/integrate_supplemental.py; private game code.\n"]
for function in functions:
    output.append(f"void {function}(uint8_t *, R5900Context *, PS2Runtime *);\n")
for function in functions:
    source = directory / (function + ".cpp")
    body = source.read_text()
    body = body.replace("#include <ps2_recompiled_functions.h>\n", "")
    body = body.replace("#include <ps2_recompiled_stubs.h>\n", "")
    source.write_text(body)
    output.append(f'#include "{source.name}"\n')
if capture is not None:
    for function in functions:
        address = int(function.rsplit("_", 1)[1], 0)
        first, second = struct.unpack_from("<II", capture, address - capture_base)
        output.append(f"static void checked_{function}(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime) {{\n")
        mask1 = 0xffff0000 if first >> 26 in (2, 3, 9, 15, 0x23, 0x2b, 0x39) else 0xffffffff
        mask2 = 0xffff0000 if second >> 26 in (2, 3, 9, 15, 0x23, 0x2b, 0x39) else 0xffffffff
        output.append(f"    if ((Ps2FastRead32(rdram, {address:#x}u) & {mask1:#x}u) != {first & mask1:#x}u || (Ps2FastRead32(rdram, {address+4:#x}u) & {mask2:#x}u) != {second & mask2:#x}u) throw std::runtime_error(\"Overlay code fingerprint mismatch: {function}\");\n")
        output.append(f"    {function}(rdram, ctx, runtime);\n}}\n")
output.append(f"static void {name}(PS2Runtime &runtime) {{\n")
for function, address in entries:
    target = "checked_" + function if capture is not None else function
    output.append(f"    if (!runtime.hasFunction({address}u)) runtime.registerFunction({address}u, {target});\n")
output.append("}\n")
(directory / "integrated.inc").write_text("".join(output))
print(f"Integrated {len(functions)} functions and {len(entries)} entrypoints")
